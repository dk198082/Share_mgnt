import ExcelJS from "exceljs";
import type { Report, ReportCell, ReportSheet } from "./report-data";

export async function reportWorkbook(report: Report): Promise<Buffer> {
  const book = new ExcelJS.Workbook();
  book.creator = report.generatedBy;
  book.created = report.generatedAt;
  book.modified = report.generatedAt;
  book.title = report.title;
  book.subject = `Data through ${report.asOfDate}; SSNs masked`;
  const sheets: ReportSheet[] = [...report.sheets, {
    name: "Notes", columns: [{ label: "Reporting notes and data limitations" }],
    rows: report.notes.map(note => [note]),
  }];
  for (const spec of sheets) {
    const sheet = book.addWorksheet(spec.name, { views: [{ state: "frozen", ySplit: 4 }] });
    sheet.getCell(1, 1).value = `${report.title} — ${spec.name}`;
    sheet.getCell(1, 1).font = { name: "Calibri", size: 18, bold: true, color: { argb: "FF193B40" } };
    sheet.getCell(2, 1).value = `Generated by ${report.generatedBy} | Data through ${report.asOfDate} | Generated ${report.generatedAt.toISOString()}`;
    sheet.getCell(2, 1).font = { size: 10, color: { argb: "FF52686B" } };
    if (spec.columns.length > 1) {
      sheet.mergeCells(1, 1, 1, spec.columns.length);
      sheet.mergeCells(2, 1, 2, spec.columns.length);
    }
    sheet.getRow(1).height = 28;
    sheet.getRow(2).height = 30;
    sheet.getCell(2, 1).alignment = { wrapText: true, vertical: "middle" };
    const header = sheet.getRow(4);
    header.values = spec.columns.map(col => col.label);
    header.height = 34;
    header.eachCell(cell => {
      cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF193B40" } };
      cell.font = { bold: true, color: { argb: "FFFFFFFF" }, size: 10 };
      cell.alignment = { wrapText: true, vertical: "middle" };
    });
    spec.columns.forEach((col, i) => {
      const column = sheet.getColumn(i + 1);
      column.width = spec.name === "Notes" ? 120 : /Name|Shareholder$|Event|Address|Comments|Vesting Schedule|Transferred To/.test(col.label) ? 34 : Math.min(28, Math.max(16, col.label.length + 2));
      column.numFmt = col.format === "percent" ? "0.0000%" : col.format === "money" ? "#,##0.00####" : col.format === "date" ? "yyyy-mm-dd" : "#,##0.########";
    });
    for (const values of spec.rows) {
      const row = sheet.addRow(values.map((value: ReportCell, index) => {
        if (typeof value === "string" && spec.columns[index]?.format === "date" && /^\d{4}-\d{2}-\d{2}$/.test(value))
          return new Date(`${value}T00:00:00Z`);
        // Identifiers/SSNs/user strings stay literal strings, never formulas.
        if (typeof value === "number" && Number.isInteger(value) && Math.abs(value) >= 1e15) return String(value);
        return value;
      }));
      row.eachCell({ includeEmpty: true }, cell => {
        cell.font = { name: "Calibri", size: 11 };
        cell.alignment = { vertical: "top", wrapText: true };
        if (row.number % 2 === 1) cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF0F5F4" } };
      });
      if (spec.name === "Notes") row.height = 42;
    }
    if (!spec.rows.length) sheet.getCell(5, 1).value = "No matching records.";
    sheet.autoFilter = { from: { row: 4, column: 1 }, to: { row: Math.max(4, 4 + spec.rows.length), column: spec.columns.length } };
    sheet.pageSetup = { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 0, printTitlesRow: "1:4" };
    sheet.headerFooter.oddFooter = "&LConfidential — employee use only&RPage &P of &N";
  }
  return Buffer.from(await book.xlsx.writeBuffer());
}
